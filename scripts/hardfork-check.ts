/**
 * Replays real transactions just before and just after each CKB-VM hardfork
 * (Mirana: v1, Meepo: v2), on mainnet and testnet, and compares the per-group
 * sum with the totals the chain's record gives: the node's `cycles` where it
 * has them, else the Nervos explorer's. Each transaction is also replayed with
 * ckb-debugger's `--script-version` forced to the other two values, so the
 * table shows whether it tells the versions apart.
 *
 * Usage:
 *   npm run hardfork                 replay the transactions in compat/hardfork.json
 *   npm run hardfork -- --discover   pick them again: for each network, fork and side,
 *                                    the transaction nearest the fork's first block of
 *                                    each kind (secp, type, data); see Kind
 *   options: [--mainnet-rpc <url>] [--testnet-rpc <url>] [--debugger <path>]
 *            [--window <blocks>] [--data-window <blocks>] [--no-fixture]
 *            [--cycles-rpc <network>=<url> ...]
 *
 * Writes compat/hardfork.json, the results section of compat/HARDFORK.md (the
 * text above its generated marker is kept), and test/fixtures/hardfork-mocks.json.br
 * (the mock transactions, for the offline test). Read-only JSON-RPC, a few
 * requests at a time. Exits 1 when a sum differs from a node's recorded total.
 */
