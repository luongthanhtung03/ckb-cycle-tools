const { values: flags } = parseArgs({
  options: {
    discover: { type: "boolean", default: false },
    "mainnet-rpc": { type: "string", default: PUBLIC_RPC.mainnet },
    "testnet-rpc": { type: "string", default: PUBLIC_RPC.testnet },
    debugger: { type: "string" },
    window: { type: "string", default: "300" },
    "data-window": { type: "string", default: "2000" },
    "no-fixture": { type: "boolean", default: false },
    "cycles-rpc": { type: "string", multiple: true },
  },
});

const DATA_FILE = "compat/hardfork.json";
const REPORT_FILE = "compat/HARDFORK.md";
const FIXTURE_FILE = "test/fixtures/hardfork-mocks.json.br";
const MARKER = "<!-- Generated by scripts/hardfork-check.ts";
const EXPLORER_API: Record<Network, string> = {
  mainnet: "https://mainnet-api.explorer.nervos.org/api/v1/transactions/",
  testnet: "https://testnet-api.explorer.nervos.org/api/v1/transactions/",
};
const SECP_LOCK = "0x9bd7e06f3ecf4be0f2fcd2188b23f1b9fcc88e5d4b65a8637b17723bbda3cce8";
const RFC: Record<Fork, string> = { mirana: "0032", meepo: "0049" };

/**
 * Nodes asked for a block's cycles after the main one. Some public nodes answer
 * 0x0 or nothing for older blocks; these two (checked 6 Nov 2026) have them
 * from each network's Mirana block on. `--cycles-rpc mainnet=<url>` replaces the list.
 */
const CYCLES_RPC: Record<Network, string[]> = {
  mainnet: ["https://mainnet.ckbapp.dev/rpc"],
  testnet: ["https://testnet.ckbapp.dev/rpc"],
};
const cyclesRpc = (n: Network) => {
  const given = (flags["cycles-rpc"] ?? []).filter((s) => s.startsWith(n + "=")).map((s) => s.slice(n.length + 1));
  return given.length ? given : CYCLES_RPC[n];
};
const rpcUrl = (n: Network) => (n === "mainnet" ? flags["mainnet-rpc"]! : flags["testnet-rpc"]!);

/** Retries network and gateway errors, with backoff; anything else is thrown. */
function retrying(url: string): Rpc {
  const base = httpRpc(url, { timeoutMs: 60_000, concurrency: 4 });
  return async <T>(method: string, params: unknown[]): Promise<T> => {
    for (let attempt = 1; ; attempt++) {
      try {
        return await base<T>(method, params);
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        if (!/cannot reach|no answer|HTTP (429|5\d\d)|did not answer with JSON-RPC/.test(msg) || attempt >= 5) throw e;
        await new Promise((r) => setTimeout(r, 2000 * 2 ** (attempt - 1)));
      }
    }
  };
}

/** The explorer's `cycles` for a transaction, as a decimal string, or null. Only that number is read. */
async function explorerCycles(network: Network, hash: string): Promise<string | null> {
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const res = await fetch(EXPLORER_API[network] + hash, {
        headers: { Accept: "application/vnd.api+json", "Content-Type": "application/vnd.api+json" },
        signal: AbortSignal.timeout(30_000),
      });
      if (res.status === 404) return null;
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const body = (await res.json()) as { data?: { attributes?: { cycles?: unknown } } };
      const c = body.data?.attributes?.cycles;
      return typeof c === "number" && Number.isSafeInteger(c) && c >= 0 ? String(c) : typeof c === "string" && /^\d+$/.test(c) ? c : null;
    } catch {
      await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
  return null;
}

type Forks = HardforkData["meta"]["forks"];

async function forksOf(rpcs: Record<Network, Rpc>): Promise<Forks> {
  const out = {} as Forks;
  for (const n of ["mainnet", "testnet"] as const) {
    const c = await nodeConsensus(rpcs[n]);
    if (c.network !== n) throw new Error(`${rpcUrl(n)} serves ${c.network}, not ${n}`);
    out[n] = {} as Forks[Network];
    for (const [fork, epoch] of [["mirana", c.vmEpochs[0]], ["meepo", c.vmEpochs[1]]] as const) {
      const e = await rpcs[n]<{ start_number: string }>("get_epoch_by_number", ["0x" + epoch.toString(16)]);
      out[n][fork] = { epoch, startBlock: Number(e.start_number) };
    }
  }
  return out;
}

/* ------------------------------------------------------------ discover */

type Block = { header: { number: string; epoch: string }; transactions: (RpcTransaction & { hash: string })[] };

/** What a transaction is, by the groups that run in it; undefined when it fits no kind (e.g. only Type ID). */
function kindOf(mock: MockTransaction): Kind | undefined {
  const groups = groupsOf(mock);
  if (groups.some((g) => g.hashType !== "type")) return "data";
  if (groups.length && groups.every((g) => g.role === "lock" && g.codeHash === SECP_LOCK)) return "secp";
  if (groups.some((g) => !(g.role === "lock" && g.codeHash === SECP_LOCK) && !g.codeHash.endsWith("545950455f4944"))) return "type";
  return undefined;
}

/**
 * For one fork and side, the transaction of each kind nearest the fork's first
 * block. secp and type are looked for within `window` blocks, data within
 * `dataWindow`: only a transaction whose outputs carry a data* type script is
 * considered for data that far out (an output's type script runs; an input's
 * data* lock would be missed).
 */
async function discoverSide(rpc: Rpc, network: Network, fork: Fork, side: Side, start: number, forkEpoch: number): Promise<Case[]> {
  const window = Number(flags.window);
  const dataWindow = Number(flags["data-window"]);
  const found = new Map<Kind, string>();
  const step = side === "before" ? -1 : 1;
  const first = side === "before" ? start - 1 : start;
  const BATCH = 8;
  for (let k = 0; k < dataWindow && found.size < 3; k += BATCH) {
    const numbers = Array.from({ length: BATCH }, (_, i) => first + step * (k + i));
    const blocks = await Promise.all(numbers.map((n) => rpc<Block>("get_block_by_number", ["0x" + n.toString(16)])));
    for (const [i, b] of blocks.entries()) {
      const epoch = Number(BigInt(b.header.epoch) & 0xffffffn);
      if ((side === "before") !== epoch < forkEpoch) throw new Error(`block ${numbers[i]} is in epoch ${epoch}, on the wrong side of ${forkEpoch}`);
      const near = k + i < window;
      for (const tx of b.transactions) {
        if (isCellbase(tx) || found.size >= 3) continue;
        const dataOutput = tx.outputs.some((o) => o.type && o.type.hash_type !== "type");
        // Within the window every transaction is looked at; past it, only one that may be of the missing data kind.
        const nearNeeded = near && !(found.has("secp") && found.has("type"));
        if (!nearNeeded && (!dataOutput || found.has("data"))) continue;
        const { mock } = await buildMockTransaction(rpc, tx.hash);
        const kind = kindOf(mock);
        if (kind && !found.has(kind) && (near || kind === "data")) {
          found.set(kind, tx.hash);
          console.log(`  ${network} ${fork} ${side}: ${kind} ${tx.hash} (block ${numbers[i]})`);
        }
      }
    }
  }
  for (const kind of ["secp", "type", "data"] as const) {
    if (!found.has(kind)) console.log(`  ${network} ${fork} ${side}: no ${kind} transaction within ${kind === "data" ? dataWindow : window} blocks`);
  }
  return (["secp", "type", "data"] as const).filter((k) => found.has(k)).map((kind) => ({ network, fork, side, kind, hash: found.get(kind)! }));
}

/* ------------------------------------------------------------ replay */

type Exec = (args: string[]) => ReturnType<typeof runNativeDebugger>;

async function replayCase(c: Case, rpc: Rpc, forks: Forks, exec: Exec, debuggerVersion: string, txFile: string) {
  // The same planning as `ckb-cycles <hash> --rpc <url>`: the mock, the groups and the VM version.
  const plan = await planReplay(c.hash, { network: c.network, rpcUrl: rpcUrl(c.network), timeoutMs: 60_000 });
  const got = await rpc<{ cycles: string | null; tx_status: { block_hash: string } }>("get_transaction", [c.hash]);
  const blockHash = got.tx_status.block_hash;
  // With `with_cycles`, get_block answers { block, cycles }: cycles lists the block's transactions without the cellbase.
  const res = await rpc<{ block: { header: { number: string; epoch: string }; transactions: { hash: string }[] }; cycles?: string[] | null }>(
    "get_block",
    [blockHash, null, true],
  );
  const block = res.block;
  const index = block.transactions.findIndex((t) => t.hash === c.hash);
  const nodes: NodeCycles[] = [{ url: rpcUrl(c.network), tx: got.cycles, block: index > 0 && res.cycles ? (res.cycles[index - 1] ?? null) : null }];
  // Nodes that kept cycles for older blocks: only the block's numbers are read from them.
  for (const url of cyclesRpc(c.network)) {
    try {
      const other = await retrying(url)<{ block: { transactions: { hash: string }[] }; cycles?: string[] | null }>("get_block", [blockHash, null, true]);
      const i = other.block.transactions.findIndex((t) => t.hash === c.hash);
      nodes.push({ url, tx: null, block: i > 0 && other.cycles ? (other.cycles[i - 1] ?? null) : null });
    } catch (e) {
      console.error(`  ${url}: ${e instanceof Error ? e.message : e}`);
      nodes.push({ url, tx: null, block: null });
    }
  }
  const epoch = Number(BigInt(block.header.epoch) & 0xffffffn);

  await writeFile(txFile, JSON.stringify(plan.mock));
  const runs = {} as Record<"0" | "1" | "2", VersionRun[]>;
  for (const v of [0, 1, 2] as const) runs[String(v) as "0" | "1" | "2"] = await runAtVersion(plan, v, exec, { txFile, debugger: debuggerVersion });
  const groups: GroupRecord[] = plan.groups.map((g, i) => {
    const name = g.name ?? runs[String(plan.scriptVersion) as "0" | "1" | "2"][i].name;
    return {
      role: g.role,
      codeHash: g.codeHash,
      hashType: g.hashType,
      ...(name && { name }),
      selector: selectorFor(g),
      vm: vmOf(g.hashType, plan.scriptVersion),
      runs: Object.fromEntries(
        (["0", "1", "2"] as const).map((v) => {
          const { name: _n, ...r } = runs[v][i];
          return [v, r];
        }),
      ) as GroupRecord["runs"],
    };
  });
  const record = judge({
    ...c,
    block: Number(block.header.number),
    epoch,
    index,
    forkEpoch: forks[c.network][c.fork].epoch,
    nodes,
    explorerCycles: await explorerCycles(c.network, c.hash),
    scriptVersion: plan.scriptVersion,
    groups,
  });
  return { record, mock: plan.mock };
}

async function main() {
  const rpcs = { mainnet: retrying(rpcUrl("mainnet")), testnet: retrying(rpcUrl("testnet")) };
  const forks = await forksOf(rpcs);
  const startedAt = new Date().toISOString();

  let cases: Case[];
  if (flags.discover) {
    cases = [];
    for (const network of ["mainnet", "testnet"] as const) {
      for (const fork of ["mirana", "meepo"] as const) {
        for (const side of ["before", "after"] as const) {
          const f = forks[network][fork];
          cases.push(...(await discoverSide(rpcs[network], network, fork, side, f.startBlock, f.epoch)));
        }
      }
    }
    // Kept before replaying, so a failed replay does not lose a long search (a plain run then replays them).
    await writeFile(DATA_FILE, JSON.stringify({ meta: { discoveredAt: startedAt }, cases }, null, 1) + "\n");
  } else {
    if (!existsSync(DATA_FILE)) throw new Error(`${DATA_FILE} not found: run with --discover first`);
    const prior = JSON.parse(await readFile(DATA_FILE, "utf8")) as HardforkData;
    cases = prior.cases.map(({ network, fork, side, kind, hash }) => ({ network, fork, side, kind, hash }));
  }

  const debuggerPath = flags.debugger ? checkDebuggerPath(flags.debugger) : resolveDebugger();
  const exec: Exec = (args) => runNativeDebugger(debuggerPath, args);
  const debuggerVersion = (await exec(["--version"])).stdout.trim() || "unknown";
  let toolCommit: string | undefined;
  try {
    toolCommit = execSync("git rev-parse HEAD", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    // Not a checkout.
  }

  const dir = await mkdtemp(join(tmpdir(), "ckb-hardfork-"));
  const records: (CaseRecord & { mock: MockTransaction })[] = [];
  try {
    for (const c of cases) {
      const { record, mock } = await replayCase(c, rpcs[c.network], forks, exec, debuggerVersion, join(dir, "tx.json"));
      records.push({ ...record, mock });
      console.log(
        `${c.network} ${c.fork} ${c.side} ${c.kind} block ${record.block} epoch ${record.epoch} ${c.hash.slice(0, 12)}: ` +
          `v${record.scriptVersion} sum ${record.sum}, total ${record.total ?? "?"} (${record.oracle ?? "none"}) ${record.verdict}; sums ${JSON.stringify(record.sums)}`,
      );
    }
  } finally {
    await rm(dir, { recursive: true, force: true });
  }

  const data: HardforkData = {
    meta: {
      startedAt,
      finishedAt: new Date().toISOString(),
      debugger: debuggerVersion,
      ...(toolCommit && { toolCommit }),
      rpc: { mainnet: rpcUrl("mainnet"), testnet: rpcUrl("testnet") },
      cyclesRpc: { mainnet: cyclesRpc("mainnet"), testnet: cyclesRpc("testnet") },
      explorer: EXPLORER_API,
      forks,
    },
    cases: records.map(({ mock: _mock, ...r }) => r),
  };
  await writeFile(DATA_FILE, JSON.stringify(data, null, 1) + "\n");
  const head = existsSync(REPORT_FILE) ? (await readFile(REPORT_FILE, "utf8")).split(MARKER)[0] : "# Replays across the CKB-VM hardforks\n\n";
  await writeFile(REPORT_FILE, head + renderMarkdown(data, "npm ci\nnpm run hardfork            # the recorded transactions\nnpm run hardfork -- --discover  # pick them again"));
  if (!flags["no-fixture"]) {
    const packed = Buffer.from(JSON.stringify(packFixture(records)));
    await writeFile(FIXTURE_FILE, brotliCompressSync(packed, { params: { [zlib.BROTLI_PARAM_QUALITY]: 11, [zlib.BROTLI_PARAM_LGWIN]: 24 } }));
  }
  const n = { match: 0, mismatch: 0, "no total": 0 };
  for (const r of data.cases) n[r.verdict]++;
  console.log(`\n${data.cases.length} transactions: ${n.match} match, ${n.mismatch} mismatch, ${n["no total"]} no total. Wrote ${DATA_FILE}, ${REPORT_FILE}${flags["no-fixture"] ? "" : `, ${FIXTURE_FILE}`}`);
  // Exit 1 only on a mismatch with a node's own number: one with the explorer alone is reported, see HARDFORK.md.
  return data.cases.some((c) => c.verdict === "mismatch" && c.oracle === "node") ? 1 : 0;
}

main().then(
  (code) => process.exit(code),
  (e) => {
    console.error(e instanceof Error ? e.message : e);
    process.exit(2);
  },
);
